import { z } from "zod";
import { DATE_REGEX } from "../constants/employee.constants";
import {
  APPROVAL_STATUS,
  PAY_STATUS,
  SALARY_APPROVAL_NAME_MAX_LENGTH,
  SALARY_BANK_ACCOUNT_MAX_LENGTH,
  SALARY_DESCRIPTION_MAX_LENGTH,
  SALARY_MONTH_ID_MAX_LENGTH,
  SALARY_STAFF_CATEGORY_MAX_LENGTH,
  SALARY_STATUS,
} from "../constants/salary.constants";

const positiveId = (label: string) =>
  z.coerce.number({ error: `${label} is required` }).int().positive(`${label} must be a valid id`);

const optionalNonNegativeInt = z.coerce.number().int().min(0).optional();

// ─── Applied allowances (optional) ──────────────────────────────────────────
// One entry per hr_allowance_types row the sheet should carry. `amount` is
// an optional override — when omitted, the service resolves it from the
// allowance type's own calculation_type/default_value (see
// salary.service.ts's resolveAllowances). See salary.constants.ts's
// "Allowances & Auto Tax Calculation" note for what providing this array
// does to gross_salary/tax_amount.
const salaryAllowanceInputSchema = z.object({
  allowance_type_id: positiveId("Allowance type"),
  amount: z.coerce.number().min(0).optional(),
});

// ─── Create Salary Sheet ──────────────────────────────────────────────────────
// sheet_code is NOT accepted here — it's generated by the service from
// branch_id/year_id/month_id/staff_id (see salary.service.ts), guaranteeing
// it's always unique and consistent rather than relying on manual entry.
// The approval-chain columns are likewise never set here; they take their DB
// defaults ('Pending') and can only be changed via updateSalaryApprovalSchema.
//
// gross_salary is required UNLESS `allowances` is provided — in that case
// it's derived server-side and any value sent here is ignored (see
// salary.service.ts).
const salaryCoreSchema = z
  .object({
    staff_id: positiveId("Employee"),
    branch_id: positiveId("Branch"),
    ledger_id: positiveId("Ledger id"),
    financial_year: positiveId("Financial year"),
    date: z
      .string({ error: "Date is required" })
      .trim()
      .regex(DATE_REGEX, "Date must be in YYYY-MM-DD format")
      .refine((val) => !Number.isNaN(new Date(val).getTime()), { message: "Date must be valid" }),
    month_id: z
      .string({ error: "Month is required" })
      .trim()
      .min(1, "Month is required")
      .max(SALARY_MONTH_ID_MAX_LENGTH),
    year_id: z.coerce.number({ error: "Year is required" }).int().min(2000).max(2100),

    staff_category: z.string().trim().max(SALARY_STAFF_CATEGORY_MAX_LENGTH).optional(),
    description: z.string().trim().max(SALARY_DESCRIPTION_MAX_LENGTH).optional(),
    bank_account: z.string().trim().max(SALARY_BANK_ACCOUNT_MAX_LENGTH).optional(),
    remarks: z.string().trim().optional(),

    gross_salary: z.coerce.number().int().min(0).optional(),
    basic_salary: optionalNonNegativeInt,
    medical_allowance: z.coerce.number().min(0).optional(),
    house_rent_allowance: z.coerce.number().min(0).optional(),
    conveyance_allowance: optionalNonNegativeInt,
    training: optionalNonNegativeInt,
    eobi_amount: optionalNonNegativeInt,
    epf_amount: optionalNonNegativeInt,
    tax_amount: optionalNonNegativeInt,
    exempt_amount: optionalNonNegativeInt,
    loan_amount: optionalNonNegativeInt,
    pay_loan: optionalNonNegativeInt,
    other_deduction: optionalNonNegativeInt,
    leaves: optionalNonNegativeInt,
    leaves_deduction: optionalNonNegativeInt,
    arrears: optionalNonNegativeInt,
    allowances: z.array(salaryAllowanceInputSchema).optional(),

    pay_status: z.union([z.literal(PAY_STATUS.YES), z.literal(PAY_STATUS.NO)]).optional(),
    salary_status: z
      .union([
        z.literal(SALARY_STATUS.PENDING),
        z.literal(SALARY_STATUS.INACTIVE),
        z.literal(SALARY_STATUS.ACTIVE),
        z.literal(SALARY_STATUS.APPROVED),
        z.literal(SALARY_STATUS.REJECTED),
        z.literal(SALARY_STATUS.PAID),
      ])
      .optional(),
  });

export const createSalarySchema = salaryCoreSchema.refine(
  (data) => data.allowances !== undefined || data.gross_salary !== undefined,
  { message: "Gross salary is required when no allowances are provided", path: ["gross_salary"] }
);

export type CreateSalaryInput = z.infer<typeof createSalarySchema>;

// ─── Update Salary Sheet (core fields — partial, but body cannot be empty) ──
export const updateSalarySchema = salaryCoreSchema
  .partial()
  .refine((data) => Object.keys(data).length > 0, {
    message: "At least one field must be provided to update the salary sheet",
  });

export type UpdateSalaryInput = z.infer<typeof updateSalarySchema>;

// ─── Update approval chain (separate endpoint/action from core edits) ───────
const approvalStatusField = z
  .union([z.literal(APPROVAL_STATUS.PENDING), z.literal(APPROVAL_STATUS.APPROVED), z.literal(APPROVAL_STATUS.REJECTED)])
  .optional();
const approverNameField = z.string().trim().max(SALARY_APPROVAL_NAME_MAX_LENGTH).optional();

export const updateSalaryApprovalSchema = z
  .object({
    ceo_status: approvalStatusField,
    ceo_approved_by: approverNameField,
    hr_status: approvalStatusField,
    hr_approved_by: approverNameField,
  })
  .refine((data) => Object.keys(data).length > 0, {
    message: "At least one approval field must be provided",
  });

export type UpdateSalaryApprovalInput = z.infer<typeof updateSalaryApprovalSchema>;

// ─── :id route param ────────────────────────────────────────────────────────
export const salaryIdParamSchema = z.object({
  id: z.coerce
    .number({ error: "Salary sheet id must be a number" })
    .int("Salary sheet id must be a valid integer")
    .positive("Salary sheet id must be a valid integer"),
});

// ─── GET /salary-sheets query params ────────────────────────────────────────
export const listSalaryQuerySchema = z.object({
  page: z.coerce.number().int().positive().optional().default(1),
  limit: z.coerce.number().int().positive().max(100).optional().default(20),
  search: z.string().trim().max(191).optional(),
  staff_id: z.coerce.number().int().positive().optional(),
  branch_id: z.coerce.number().int().positive().optional(),
  company_id: z.coerce.number().int().positive().optional(),
  month_id: z.string().trim().optional(),
  year_id: z.coerce.number().int().optional(),
  salary_status: z
    .union([
      z.literal(SALARY_STATUS.PENDING),
      z.literal(SALARY_STATUS.INACTIVE),
      z.literal(SALARY_STATUS.ACTIVE),
      z.literal(SALARY_STATUS.APPROVED),
      z.literal(SALARY_STATUS.REJECTED),
      z.literal(SALARY_STATUS.PAID),
    ])
    .optional(),
});
