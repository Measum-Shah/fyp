import React, { useState, useEffect } from "react";
import { StudentAPI } from "../services/api";

interface CourseRow {
  course_no: string;
  course_title: string;
  credit_hours: number;
  marks: number;
  total_marks: number;
  letter_grade: string;
  grade_point: number;
  percentage: number;
}

interface SemesterResult {
  term_id: number;
  term_name: string;
  session_name: string;
  gpa: string;
  courses: CourseRow[];
}

interface Transcript {
  reg_no: string | null;
  semesters: SemesterResult[];
  cgpa: string;
  total_semesters: number;
}

const getGradeColor = (grade: string) => {
  if (["A", "A+", "A-"].includes(grade)) return "#16a34a";
  if (["B+", "B", "B-"].includes(grade)) return "#2563eb";
  if (["C+", "C", "C-"].includes(grade)) return "#d97706";
  if (["D", "D+"].includes(grade)) return "#ea580c";
  return "#dc2626";
};

const StudentResultsPage: React.FC = () => {
  const [transcript, setTranscript] = useState<Transcript | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    StudentAPI.getTranscript()
      .then((res) => {
        setTranscript(res.data.data);
      })
      .catch((err) => {
        console.error("Transcript error:", err);
        setError("Could not load results. Please try again later.");
      })
      .finally(() => setLoading(false));
  }, []);

  const handlePrint = () => {
    window.print();
  };

  if (loading) {
    return (
      <div style={{ display: "flex", justifyContent: "center", alignItems: "center", minHeight: 300 }}>
        <div style={{ width: 36, height: 36, border: "3px solid var(--accent)", borderTopColor: "transparent", borderRadius: "50%", animation: "spin 0.8s linear infinite" }} />
      </div>
    );
  }

  if (error) {
    return (
      <div style={{ textAlign: "center", padding: "3rem", color: "var(--text-secondary)" }}>
        <p>{error}</p>
      </div>
    );
  }

  if (!transcript || transcript.semesters.length === 0) {
    return (
      <div style={{ textAlign: "center", padding: "3rem", color: "var(--text-secondary)" }}>
        <svg width="60" height="60" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.5" style={{ margin: "0 auto 1rem", display: "block", opacity: 0.4 }}>
          <path d="M9 17v-2m3 2v-4m3 4v-6m2 10H7a2 2 0 01-2-2V5a2 2 0 012-2h5.586a1 1 0 01.707.293l5.414 5.414a1 1 0 01.293.707V19a2 2 0 01-2 2z" />
        </svg>
        <p style={{ fontWeight: 600, fontSize: "1rem" }}>No results published yet.</p>
        <p style={{ fontSize: "0.875rem", marginTop: 4 }}>
          Your semester results will appear here once they are generated by the admin.
        </p>
      </div>
    );
  }

  return (
    <div className="flex flex-col gap-6">
      {/* ── Page Header ───────────────────────────────────── */}
      <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", flexWrap: "wrap", gap: 12 }}>
        <div>
          <h1 className="text-2xl font-bold" style={{ color: "var(--text-dark)" }}>Academic Transcript</h1>
          <p style={{ color: "var(--text-secondary)", fontSize: "0.875rem", marginTop: 2 }}>
            Reg. No: <strong>{transcript.reg_no || "—"}</strong>
          </p>
        </div>

        <div style={{ display: "flex", alignItems: "center", gap: 12 }}>
          {/* CGPA Badge */}
          <div style={{
            background: "linear-gradient(135deg, var(--accent), #6366f1)",
            color: "#fff",
            borderRadius: 12,
            padding: "10px 20px",
            textAlign: "center",
            boxShadow: "0 4px 12px rgba(0,0,0,0.15)"
          }}>
            <div style={{ fontSize: "0.72rem", opacity: 0.85, letterSpacing: "0.5px", textTransform: "uppercase" }}>Cumulative GPA</div>
            <div style={{ fontSize: "1.75rem", fontWeight: 800, lineHeight: 1.1 }}>{transcript.cgpa}</div>
            <div style={{ fontSize: "0.7rem", opacity: 0.75 }}>
              {transcript.total_semesters} Semester{transcript.total_semesters !== 1 ? "s" : ""} Completed
            </div>
          </div>

          {/* Print */}
          <button onClick={handlePrint} style={{
            display: "flex", alignItems: "center", gap: 6,
            padding: "8px 16px", borderRadius: 8,
            background: "var(--card-bg)", border: "1px solid var(--card-border)",
            color: "var(--text-dark)", cursor: "pointer", fontWeight: 500, fontSize: "0.875rem"
          }}>
            <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
              <polyline points="6 9 6 2 18 2 18 9" />
              <path d="M6 18H4a2 2 0 01-2-2v-5a2 2 0 012-2h16a2 2 0 012 2v5a2 2 0 01-2 2h-2" />
              <rect x="6" y="14" width="12" height="8" />
            </svg>
            Print
          </button>
        </div>
      </div>

      {/* ── Semester Blocks ────────────────────────────────── */}
      {transcript.semesters.map((sem, idx) => (
        <div key={idx} className="panel-card" style={{ overflow: "hidden" }}>

          {/* Semester Header (coloured bar like COMSATS) */}
          <div style={{
            display: "flex", justifyContent: "space-between", alignItems: "center",
            padding: "12px 20px",
            background: "linear-gradient(90deg, var(--accent) 0%, #6366f1 100%)",
            color: "#fff"
          }}>
            <div>
              <div style={{ fontWeight: 700, fontSize: "1rem" }}>{sem.term_name}</div>
              {sem.session_name && (
                <div style={{ fontSize: "0.8rem", opacity: 0.85 }}>{sem.session_name}</div>
              )}
            </div>
            <div style={{ textAlign: "right" }}>
              <div style={{ fontSize: "0.72rem", opacity: 0.8 }}>Semester GPA</div>
              <div style={{ fontSize: "1.4rem", fontWeight: 800 }}>{sem.gpa}</div>
            </div>
          </div>

          {/* Course Table */}
          {sem.courses.length === 0 ? (
            <div style={{ padding: "1.5rem", textAlign: "center", color: "var(--text-secondary)", fontSize: "0.875rem" }}>
              No course details available for this semester.
            </div>
          ) : (
            <div style={{ overflowX: "auto" }}>
              <table style={{ width: "100%", borderCollapse: "collapse", fontSize: "0.875rem" }}>
                <thead>
                  <tr style={{ background: "var(--input-bg)", borderBottom: "2px solid var(--card-border)" }}>
                    <th style={thStyle}>Course No</th>
                    <th style={{ ...thStyle, textAlign: "left" }}>Course Title</th>
                    <th style={thStyle}>Credit</th>
                    <th style={thStyle}>Marks</th>
                    <th style={thStyle}>%</th>
                    <th style={thStyle}>L.G.</th>
                    <th style={thStyle}>G.P.</th>
                  </tr>
                </thead>
                <tbody>
                  {sem.courses.map((course, ci) => (
                    <tr key={ci} style={{
                      borderBottom: "1px solid var(--card-border)",
                      background: ci % 2 === 0 ? "var(--card-bg)" : "var(--input-bg)"
                    }}>
                      <td style={{ ...tdStyle, fontWeight: 600, color: "var(--accent)", fontFamily: "monospace", textAlign: "center" }}>
                        {course.course_no}
                      </td>
                      <td style={{ ...tdStyle, textAlign: "left" }}>
                        {course.course_title}
                      </td>
                      <td style={{ ...tdStyle, textAlign: "center" }}>{course.credit_hours}</td>
                      <td style={{ ...tdStyle, textAlign: "center" }}>
                        {course.total_marks > 0 ? `${course.marks} / ${course.total_marks}` : "NC"}
                      </td>
                      <td style={{ ...tdStyle, textAlign: "center" }}>
                        {course.percentage ? `${course.percentage}%` : "—"}
                      </td>
                      <td style={{ ...tdStyle, textAlign: "center" }}>
                        <span style={{ fontWeight: 700, fontSize: "0.95rem", color: getGradeColor(course.letter_grade) }}>
                          {course.letter_grade}
                        </span>
                      </td>
                      <td style={{ ...tdStyle, textAlign: "center", fontWeight: 600 }}>
                        {course.grade_point || "NC"}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}

          {/* Semester Summary Footer */}
          <div style={{
            padding: "10px 20px",
            background: "var(--input-bg)",
            borderTop: "1px solid var(--card-border)",
            display: "flex",
            gap: 28,
            fontSize: "0.875rem",
            color: "var(--text-dark)"
          }}>
            <span><strong>GPA:</strong> {sem.gpa}</span>
            <span><strong>Courses:</strong> {sem.courses.length}</span>
            <span><strong>Total Credits:</strong> {sem.courses.reduce((s, c) => s + (c.credit_hours || 0), 0)}</span>
          </div>
        </div>
      ))}

      {/* ── Overall CGPA Summary Card ──────────────────────── */}
      <div className="panel-card" style={{ padding: "1.5rem" }}>
        <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", flexWrap: "wrap", gap: 16 }}>
          <div>
            <h3 style={{ margin: 0, color: "var(--text-dark)" }}>Overall Academic Performance</h3>
            <p style={{ margin: "4px 0 0", color: "var(--text-secondary)", fontSize: "0.875rem" }}>
              Based on {transcript.total_semesters} completed semester(s)
            </p>
          </div>
          <div style={{ display: "flex", gap: 12, flexWrap: "wrap" }}>
            <div style={summaryCard("#dcfce7", "#16a34a")}>
              <div style={{ fontSize: "0.7rem", textTransform: "uppercase", opacity: 0.7 }}>CGPA</div>
              <div style={{ fontSize: "2rem", fontWeight: 800 }}>{transcript.cgpa}</div>
              <div style={{ fontSize: "0.7rem" }}>out of 4.00</div>
            </div>
            <div style={summaryCard("#dbeafe", "#2563eb")}>
              <div style={{ fontSize: "0.7rem", textTransform: "uppercase", opacity: 0.7 }}>Semesters</div>
              <div style={{ fontSize: "2rem", fontWeight: 800 }}>{transcript.total_semesters}</div>
              <div style={{ fontSize: "0.7rem" }}>Completed</div>
            </div>
            <div style={summaryCard("#fef9c3", "#ca8a04")}>
              <div style={{ fontSize: "0.7rem", textTransform: "uppercase", opacity: 0.7 }}>Scholastic Status</div>
              <div style={{ fontSize: "1rem", fontWeight: 700, marginTop: 6 }}>
                {parseFloat(transcript.cgpa) >= 3.5
                  ? "Distinction"
                  : parseFloat(transcript.cgpa) >= 3.0
                  ? "Good Standing"
                  : parseFloat(transcript.cgpa) >= 2.0
                  ? "Satisfactory"
                  : "Probation"}
              </div>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};

/* ─── Shared style helpers ──────────────────────────────── */
const thStyle: React.CSSProperties = {
  padding: "10px 12px",
  textAlign: "center",
  fontWeight: 600,
  color: "var(--text-dark)",
  whiteSpace: "nowrap",
  fontSize: "0.78rem",
  textTransform: "uppercase",
  letterSpacing: "0.4px"
};

const tdStyle: React.CSSProperties = {
  padding: "10px 12px",
  color: "var(--text-dark)",
  verticalAlign: "middle"
};

const summaryCard = (bg: string, color: string): React.CSSProperties => ({
  background: bg,
  color,
  borderRadius: 10,
  padding: "12px 20px",
  textAlign: "center",
  minWidth: 100
});

export default StudentResultsPage;
